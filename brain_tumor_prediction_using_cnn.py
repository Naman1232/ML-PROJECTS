IMG_SIZE = 128

def resize_images(images, size=IMG_SIZE):
    resized = []
    for img in images:
        img_resized = cv2.resize(img, (size, size))
        resized.append(img_resized)
    return np.array(resized)

denoised_images = resize_images(denoised_images)

def generate_pseudo_masks(images):
    masks = []
    for img in images:
        flat_img = img.reshape(-1, 3)
        kmeans = KMeans(n_clusters=2, random_state=42).fit(flat_img)
        clustered = kmeans.labels_.reshape(img.shape[:2])
        # Convert clustered map to binary mask
        mask = (clustered == clustered[0, 0]).astype(np.uint8)  # background vs tumor
        mask = 1 - mask  # make tumor region = 1
        masks.append(mask)
    return np.array(masks)

pseudo_masks = generate_pseudo_masks(denoised_images)
pseudo_masks = np.expand_dims(pseudo_masks, axis=-1)

def build_unet(input_shape=(128, 128, 3)):
    inputs = Input(input_shape)

    c1 = Conv2D(16, 3, activation='relu', padding='same')(inputs)
    c1 = Conv2D(16, 3, activation='relu', padding='same')(c1)
    p1 = MaxPooling2D()(c1)

    c2 = Conv2D(32, 3, activation='relu', padding='same')(p1)
    c2 = Conv2D(32, 3, activation='relu', padding='same')(c2)
    p2 = MaxPooling2D()(c2)

    c3 = Conv2D(64, 3, activation='relu', padding='same')(p2)
    c3 = Conv2D(64, 3, activation='relu', padding='same')(c3)

    u1 = UpSampling2D()(c3)
    u1 = Concatenate()([u1, c2])
    c4 = Conv2D(32, 3, activation='relu', padding='same')(u1)
    c4 = Conv2D(32, 3, activation='relu', padding='same')(c4)

    u2 = UpSampling2D()(c4)
    u2 = Concatenate()([u2, c1])
    c5 = Conv2D(16, 3, activation='relu', padding='same')(u2)
    c5 = Conv2D(16, 3, activation='relu', padding='same')(c5)

    outputs = Conv2D(1, 1, activation='sigmoid')(c5)

    model = Model(inputs, outputs)
    return model

unet = build_unet()
unet.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
unet.summary()

